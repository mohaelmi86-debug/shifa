// ─── SHIFA Professional Workspace Engine ─────────────────────────────────────
// ProfessionConfigRegistry — Single source of truth for all profession configs
// Each profession declares: label, icon, category, modules (ordered), and role-specific tabs

export type ProfessionCategory =
  | 'liberal'       // Professions libérales / cabinet privé
  | 'hospital'      // Spécialités hospitalières
  | 'paramedical'   // Professions paramédicales
  | 'pharmacy'      // Pharmacie & biologie
  | 'support'       // Fonctions support & médico-sociales
  | 'institution';  // Institutionnel / santé publique

export interface WorkspaceModule {
  id: string;
  label: string;
  icon: string;
  href?: string;          // optional deep-link to existing page
  description?: string;
}

export interface ProfessionConfig {
  id: string;
  label: string;
  labelFr: string;
  icon: string;
  category: ProfessionCategory;
  color: string;           // accent color for the workspace
  modules: WorkspaceModule[];
  quickStats: QuickStat[];
  roles?: string[];        // sub-roles within this profession
}

export interface QuickStat {
  label: string;
  value: string;
  icon: string;
  trend?: 'up' | 'down' | 'neutral';
}

